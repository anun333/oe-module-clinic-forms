<?php

/**
 * Writes CONFORMANCE.md: every shipped document, what it is held to (its rule's elements, LOINC's
 * reference for a validated instrument, its publisher's wording for another, or nothing outside
 * for our own), how that is checked, and whether it is held back from release and why. Generated
 * from src/Paper/Conformance.php, the same rules tests/Paper/ConformanceTest.php enforces.
 *
 *     php tools/conformance.php            write CONFORMANCE.md
 *     php tools/conformance.php --check    exit 1 if CONFORMANCE.md is stale
 *
 * @package   OpenHealthcare\ClinicForms
 * @link      https://github.com/anun333/oe-module-clinic-forms
 * @author    anun333 <anun333@posteo.net>
 * @copyright Copyright (c) 2026 anun333 <anun333@posteo.net>
 * @license   https://www.gnu.org/licenses/gpl-3.0.html GNU General Public License 3
 */

declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    // Composer installs the package under the web root; the tools are for the command line only.
    http_response_code(404);
    exit;
}

require dirname(__DIR__) . '/vendor/autoload.php';

use OpenHealthcare\ClinicForms\Paper\Conformance;
use OpenHealthcare\ClinicForms\Paper\DocumentLibrary;
use OpenHealthcare\ClinicForms\Paper\Requirements;

$out = dirname(__DIR__) . '/CONFORMANCE.md';
$requirements = Requirements::shipped();
$rows = [];
$counts = [];
$problems = 0;
foreach (DocumentLibrary::shipped()->all() as $doc) {
    $c = Conformance::of($doc, $requirements);
    $problems += count($c['problems']);
    $counts[$c['kind']] = ($counts[$c['kind']] ?? 0) + 1;
    $rows[$c['kind']][] = [$doc, $c];
}
$cell = static fn(string $s): string => str_replace(['|', "\n"], ['\\|', ' '], $s);
$md = [];
$md[] = '# Conformance';
$md[] = '';
$md[] = 'Generated by `tools/conformance.php` from `src/Paper/Conformance.php`, the rules `tests/Paper/ConformanceTest.php` enforces. Do not edit; run `php tools/conformance.php` after changing a document, and `--check` in CI.';
$md[] = '';
$md[] = 'Every shipped document is held to what it claims to follow, by the kind of its source:';
$md[] = '';
$md[] = '- **Rule:** every element of its rule is present (`data/requirements.json`, `data/packs/us/requirements.json`).';
$md[] = '- **Instrument:** a validated one matches LOINC\'s reference question by question, with its answers, points and score range (`data/instruments`). Any other carries its publisher\'s wording unchanged (`data/references`).';
$md[] = '- **Written:** our own wording. Nothing outside to hold it to; patient documents are held to a reading level of grade 8 or below.';
$md[] = '';
$md[] = 'A document not cleared for public release is held, with its reason (`data/release-gates.json`): it ships as a draft, marked Draft in the picker and on every printed page, and in no packet. A document whose answers carry SNOMED CT US Extension codes is held whether listed or not.';
$md[] = '';
$md[] = 'Checked beside this, outside the module: every FHIR export against FHIR R4 and SDC 4.0.0 (the HL7 validator), skip logic and totals in OpenEMR\'s own questionnaire runtime, and patient PDFs against PDF/UA-1. The README says where.';
$md[] = '';
$md[] = '**' . array_sum($counts) . ' documents:** ' . implode(', ', array_map(static fn(string $k, int $n): string => "$n $k", array_keys($counts), $counts)) . '. '
    . ($problems === 0 ? 'Nothing out of conformance.' : "**$problems problems.**")
    . ' Held for release: ' . (Conformance::held() === [] ? 'none' : implode(', ', array_map(static fn(string $id): string => "`$id`", array_keys(Conformance::held())))) . '.';
$md[] = '';
foreach (['rule' => 'Written to a rule', 'instrument' => 'Published instruments', 'written' => 'Our own'] as $kind => $heading) {
    if (!isset($rows[$kind])) {
        continue;
    }
    $md[] = "## $heading";
    $md[] = '';
    $md[] = '| Document | Held to | Checked | Release |';
    $md[] = '|---|---|---|---|';
    foreach ($rows[$kind] as [$doc, $c]) {
        $release = $c['held'] !== null ? '**held:** ' . $c['held'] : ($c['problems'] === [] ? 'cleared' : '**' . implode('; ', $c['problems']) . '**');
        $md[] = '| `' . $doc->id . '` (' . $doc->audience . ') | ' . $cell($c['spec']) . ' | ' . $cell(implode('; ', $c['checks'])) . ' | ' . $cell($release) . ' |';
    }
    $md[] = '';
}
$text = implode("\n", $md);

if (in_array('--check', $argv, true)) {
    $current = is_file($out) ? (string)file_get_contents($out) : '';
    if ($current !== $text) {
        fwrite(STDERR, "CONFORMANCE.md is stale; run php tools/conformance.php\n");
        exit(1);
    }
    echo "CONFORMANCE.md is current\n";
    exit(0);
}
file_put_contents($out, $text);
echo 'wrote CONFORMANCE.md (' . array_sum($counts) . " documents, $problems problems)\n";
